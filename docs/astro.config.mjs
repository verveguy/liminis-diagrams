// @ts-check
import { defineConfig } from 'astro/config'
import starlight from '@astrojs/starlight'
import react from '@astrojs/react'
import { fileURLToPath } from 'node:url'
import { remarkC4 } from './src/plugins/remark-c4.mjs'

// Served as a GitHub Pages project site. The account has a custom domain on the
// user site, so this resolves to https://v3rv.com/liminis-diagrams/ rather than
// verveguy.github.io — the subpath is the same either way.
//
// The demo is a separate Vite app built with base '/liminis-diagrams/demo/' and
// copied into this site's output by .github/workflows/pages.yml. Nothing here
// builds it, and Astro cannot see it, so links to it are external as far as the
// link checker is concerned.
export default defineConfig({
  // `@site` so remark-c4's injected import resolves from any page depth. See
  // the note beside IMPORT_FROM in that plugin.
  vite: {
    resolve: {
      alias: { '@site': fileURLToPath(new URL('./src', import.meta.url)) },
    },
  },
  // Turns ```c4 fences into live islands. Files stay readable as markdown on
  // GitHub, where the fence renders as a code block, and gain the interactive
  // renderer here. See src/plugins/remark-c4.mjs.
  markdown: { remarkPlugins: [remarkC4] },
  site: 'https://v3rv.com',
  base: '/liminis-diagrams',
  // React is here for embedded applets: a live C4 editor on the page that
  // explains it. Astro ships static HTML and hydrates only components marked
  // with a client directive, so a page carrying several playgrounds does not
  // pay for all of them up front — use `client:visible` rather than
  // `client:load` unless an applet must be interactive above the fold.
  integrations: [
    react(),
    starlight({
      customCss: ['./src/styles/playground.css'],
      title: '@liminis/diagrams',
      description:
        'C4 architecture diagrams for JavaScript: parse C4-PlantUML, lay out with dagre, render to SVG.',
      social: { github: 'https://github.com/verveguy/liminis-diagrams' },
      editLink: {
        // Starlight appends the page's path from the *Astro project root* —
        // `src/content/docs/<page>.mdx` — so this base is the project root's
        // location in the repository, which is docs/. Verified against the
        // deployed site rather than reasoned about: an earlier attempt to
        // "correct" this to .../docs/src/content/docs/ produced a doubled path.
        baseUrl: 'https://github.com/verveguy/liminis-diagrams/edit/main/docs/',
      },
      sidebar: [
        {
          // The demo is a separate Vite app staged into this site's output, so
          // Astro cannot see it and it can never appear in an autogenerated
          // group. Without an explicit entry there is no path to it from any
          // page but the homepage, which is a live editor nobody can find.
          label: 'Demo',
          link: '/demo/',
          attrs: { target: '_self' },
        },
        {
          label: 'Building on this package',
          items: [
            { label: 'Overview', link: '/' },
            { label: 'Playground', link: '/playground/' },
            { label: 'Architecture', link: '/architecture/' },
            { label: 'C4-PlantUML reference', link: '/dsl-reference/' },
            { label: 'Data model', link: '/data-model/' },
            { label: 'Recipes', link: '/recipes/' },
          ],
        },
        {
          // Two ways to get diagrams rendered somewhere that is not this site.
          // Filed apart from the build-on-it pages because they are about
          // wiring the package into someone else's pipeline, not about its API.
          label: 'Integrations',
          items: [
            { label: 'GitHub', link: '/github-integration/' },
            { label: 'Claude Code', link: '/claude-code-integration/' },
          ],
        },
      ],
    }),
  ],
})
